using System.Text.Json.Serialization;

namespace JXReborn.ClientDriver;

/// <summary>
/// Local player entity &amp; coordinate snapshot from <c>KPlayer</c> / <c>KNpc</c> / <c>KSubWorld</c>.
/// </summary>
public sealed record PlayerSnapshot(
    [property: JsonPropertyName("in_world")] bool InWorld,
    [property: JsonPropertyName("npc_index")] int NpcIndex,
    [property: JsonPropertyName("dw_id")] uint DwId,
    [property: JsonPropertyName("name_tcvn3_hex")] string NameTcvn3Hex,
    [property: JsonPropertyName("level")] int Level,
    [property: JsonPropertyName("kind")] int Kind,
    [property: JsonPropertyName("series")] int Series,
    [property: JsonPropertyName("camp")] int Camp,
    [property: JsonPropertyName("current_camp")] int CurrentCamp,
    [property: JsonPropertyName("doing")] int Doing,
    [property: JsonPropertyName("life")] int Life,
    [property: JsonPropertyName("life_max")] int LifeMax,
    [property: JsonPropertyName("mana")] int Mana,
    [property: JsonPropertyName("mana_max")] int ManaMax,
    [property: JsonPropertyName("stamina")] int Stamina,
    [property: JsonPropertyName("stamina_max")] int StaminaMax,
    [property: JsonPropertyName("money")] int Money,
    [property: JsonPropertyName("run_status")] int RunStatus,
    [property: JsonPropertyName("pk_flag")] int PkFlag,
    [property: JsonPropertyName("pk_value")] int PkValue,
    [property: JsonPropertyName("lead_exp")] int LeadExp,
    [property: JsonPropertyName("attr_points")] int AttrPoints,
    [property: JsonPropertyName("world_rank")] int WorldRank,
    [property: JsonPropertyName("fight_mode")] int FightMode,
    [property: JsonPropertyName("ride_horse")] int RideHorse,
    [property: JsonPropertyName("map_id")] int MapId,
    [property: JsonPropertyName("subworld_idx")] int SubWorldIndex,
    [property: JsonPropertyName("region_idx")] int RegionIndex,
    [property: JsonPropertyName("map_x")] int MapX,
    [property: JsonPropertyName("map_y")] int MapY,
    [property: JsonPropertyName("mps_x")] int MpsX,
    [property: JsonPropertyName("mps_y")] int MpsY,
    [property: JsonPropertyName("sync_ready")] bool SyncReady = false,
    [property: JsonPropertyName("region_loaded")] bool RegionLoaded = false,
    [property: JsonPropertyName("save_money")] int SaveMoney = 0,
    [property: JsonPropertyName("skill_points")] int SkillPoints = 0,
    [property: JsonPropertyName("cur_faction")] int CurFaction = -1,
    [property: JsonPropertyName("first_faction")] int FirstFaction = -1,
    [property: JsonPropertyName("des_x")] int DesX = 0,
    [property: JsonPropertyName("des_y")] int DesY = 0,
    [property: JsonPropertyName("scene_focus_rx")] int SceneFocusRx = 0,
    [property: JsonPropertyName("scene_focus_ry")] int SceneFocusRy = 0,
    [property: JsonPropertyName("scene_first_to_load")] int SceneFirstToLoad = -1,
    [property: JsonPropertyName("scene_proc_mask")] int SceneProcMask = 0,
    [property: JsonPropertyName("process_ai")] int ProcessAi = 1,
    [property: JsonPropertyName("lock_move")] int LockMove = 0,
    [property: JsonPropertyName("pause_send")] int PauseSend = 0,
    [property: JsonPropertyName("npc_node_ref")] int NpcNodeRef = -1,
    [property: JsonPropertyName("no_move_byte")] int NoMoveByte = 0,
    [property: JsonPropertyName("freeze_time")] int FreezeTime = 0,
    [property: JsonPropertyName("subworld_center_slot")] int SubWorldCenterSlot = -1,
    [property: JsonPropertyName("reg_dw_id")] uint RegionDwId = 0,
    [property: JsonPropertyName("reg_con_left")] int RegionConnectLeft = -2,
    [property: JsonPropertyName("exp")] long Exp = 0,
    [property: JsonPropertyName("strength")] int Strength = 0,
    [property: JsonPropertyName("dexterity")] int Dexterity = 0,
    [property: JsonPropertyName("vitality")] int Vitality = 0,
    [property: JsonPropertyName("energy")] int Energy = 0,
    [property: JsonPropertyName("cur_strength")] int CurStrength = 0,
    [property: JsonPropertyName("cur_dexterity")] int CurDexterity = 0,
    [property: JsonPropertyName("cur_vitality")] int CurVitality = 0,
    [property: JsonPropertyName("cur_energy")] int CurEnergy = 0,
    [property: JsonPropertyName("hand_item_idx")] int HandItemIdx = 0,
    [property: JsonPropertyName("enmity_state")] int EnmityState = 0,
    [property: JsonPropertyName("enmity_aim")] int EnmityAim = 0,
    [property: JsonPropertyName("enmity_time")] int EnmityTime = 0,
    [property: JsonPropertyName("exercise_state")] int ExerciseState = 0,
    [property: JsonPropertyName("exercise_aim")] int ExerciseAim = 0,
    [property: JsonPropertyName("chat_channel_mask")] uint ChatChannelMask = 0,
    [property: JsonPropertyName("menu_state")] int MenuState = 0,
    [property: JsonPropertyName("menu_state_spr")] string MenuStateSpr = "",
    [property: JsonPropertyName("active_aura_skill_id")] int ActiveAuraSkillId = 0)
{
    [JsonIgnore]
    public string Name => HexTcvn3Decoder.Decode(NameTcvn3Hex);
}
